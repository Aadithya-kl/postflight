const customRegistry = new Map<PlatformId, PlatformSpec>();

export function getPlatformSpec(id: PlatformId): PlatformSpec {
  const custom = customRegistry.get(id);
  if (custom) return custom;
  return BUILTIN_SPECS[id];
}

export function listPlatformSpecs(): PlatformSpec[] {
  return PLATFORM_IDS.map((id) => getPlatformSpec(id));
}

export function registerPlatformSpec(spec: PlatformSpec): void {
  customRegistry.set(spec.id, spec);
}

export function resetPlatformSpecs(): void {
  customRegistry.clear();
}

export function isPlatformId(value: string): value is PlatformId {
  return (PLATFORM_IDS as readonly string[]).includes(value);
}
